/**
 * Regenerates web/locales/registry.ts from the JSON files in web/locales/,
 * so adding a language is just dropping in one `<bcp47>.json` file.
 *
 *   bun scripts/generate-locale-registry.mjs            rewrite registry.ts
 *   bun scripts/generate-locale-registry.mjs --check    fail when registry.ts drifts
 *
 * Static imports are required because the desktop app compiles with
 * `bun build --compile`, which does not expand `import.meta.glob`, and the
 * installed `web/locales/` directory is not guaranteed to exist on disk.
 * This script keeps the registry in sync automatically instead of asking
 * translators to edit TypeScript.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES_DIR = join(ROOT, "web", "locales");
const REGISTRY_PATH = join(LOCALES_DIR, "registry.ts");

function discover() {
  return readdirSync(LOCALES_DIR)
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.slice(0, -".json".length))
    .sort();
}

function varName(lang) {
  // "zh-CN" -> "zh_CN", "en-US" -> "en_US"
  return lang.replace(/[^a-zA-Z0-9]/g, "_");
}

export function generate() {
  const langs = discover();
  const imports = langs.map((l) => `import ${varName(l)} from "./${l}.json";`);
  const entries = langs.map((l) => `  "${l}": ${varName(l)},`);
  return `// AUTO-GENERATED by scripts/generate-locale-registry.mjs — do not edit manually.
// Run \`bun run i18n:locales\` after adding/removing a file in web/locales/.
${imports.join("\n")}

export const catalogs: Record<string, Record<string, string>> = {
${entries.join("\n")}
};
`;
}

const check = process.argv.includes("--check");
const next = generate();
if (check) {
  const current = readFileSync(REGISTRY_PATH, "utf8");
  if (current !== next) {
    console.error("web/locales/registry.ts is out of sync. Run: bun run i18n:locales");
    process.exit(1);
  }
  console.log(`registry.ts is in sync (${discover().length} locales).`);
} else {
  writeFileSync(REGISTRY_PATH, next);
  console.log(`Wrote ${REGISTRY_PATH} (${discover().length} locales).`);
}
